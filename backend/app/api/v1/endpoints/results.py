from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.api.access import get_owned_assessment
from app.api.deps import get_current_user
from app.core.constants import ASSESSMENT_COMPLETED
from app.db.database import get_db
from app.models.assessment import Assessment
from app.models.result import ScreeningResult
from app.models.user import User
from app.schemas.result import ScreeningResultCreate, ScreeningResultResponse

router = APIRouter(prefix="/results", tags=["Screening Results"])

_DUPLICATE = "A result already exists for this assessment"


def _owned_results(db: Session, user: User):
    return (
        db.query(ScreeningResult)
        .join(Assessment, Assessment.id == ScreeningResult.assessment_id)
        .filter(Assessment.user_id == user.id)
    )


@router.post("/", response_model=ScreeningResultResponse, status_code=201)
def create_result(
    result_data: ScreeningResultCreate,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
):
    """Store the output of the screening model for a completed assessment.

    One result per assessment; it is never generated by the API itself.
    """
    assessment = get_owned_assessment(db, user, result_data.assessment_id)

    if assessment.status != ASSESSMENT_COMPLETED:
        raise HTTPException(
            status_code=409,
            detail="Results can only be saved for completed assessments",
        )
    if assessment.result is not None:
        raise HTTPException(status_code=409, detail=_DUPLICATE)

    result = ScreeningResult(**result_data.model_dump())
    db.add(result)
    try:
        db.commit()
    except IntegrityError:
        db.rollback()
        raise HTTPException(status_code=409, detail=_DUPLICATE) from None
    db.refresh(result)
    return result


@router.get("/", response_model=list[ScreeningResultResponse])
def list_results(
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
):
    return _owned_results(db, user).order_by(ScreeningResult.id).all()


@router.get("/{result_id}", response_model=ScreeningResultResponse)
def get_result(
    result_id: int,
    db: Session = Depends(get_db),
    user: User = Depends(get_current_user),
):
    result = _owned_results(db, user).filter(ScreeningResult.id == result_id).first()
    if result is None:
        raise HTTPException(status_code=404, detail="Screening result not found")
    return result
